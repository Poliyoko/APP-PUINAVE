def _json(value: Any) -> str:
    return json.dumps(
        value,
        ensure_ascii=False,
        separators=(",", ":"),
    )


def registro_to_params(registro: RegistroLexico) -> tuple[Any, ...]:
    """Convierte RegistroLexico al contrato parametrizado PostgreSQL."""

    errores = registro.validar_minimo()
    if errores:
        raise ValueError("; ".join(errores))

    origen = asdict(registro.origen) if registro.origen is not None else None

    desconocidos = [
        asdict(item)
        for item in registro.campos_desconocidos
    ]

    return (
        registro.identificador,
        registro.palabra_puinave,
        registro.traduccion_espanol,
        registro.traduccion_ingles,
        registro.categoria_gramatical,
        registro.categoria_tematica,
        registro.tema_cultural,
        registro.descripcion_cultural,
        registro.contexto_uso,
        registro.comunidad,
        registro.territorio,
        registro.imagen,
        registro.audio_puinave,
        registro.audio_espanol,
        registro.audio_ingles,
        registro.video,
        registro.nivel_acceso,
        registro.autorizacion_publicacion,
        registro.estado_validacion,
        _json(origen),
        _json(registro.extensiones),
        _json(desconocidos),
        RLB_SCHEMA_VERSION,
    )


def ensure_schema(connection: Any) -> None:
    """Materializa el foundation RLB dentro de una transacción externa."""

    with connection.cursor() as cursor:
        cursor.execute(DDL)


def upsert_registro(connection: Any, registro: RegistroLexico) -> int:
    """Crea o actualiza idempotentemente un RegistroLexico por identificador."""

    if (
        registro.identificador is None
        or not registro.identificador.strip()
    ):
        raise ValueError(
            "identificador es obligatorio para persistencia idempotente."
        )

    params = registro_to_params(registro)

    with connection.cursor() as cursor:
        cursor.execute(INSERT_SQL, params)
        row = cursor.fetchone()

    if row is None:
        raise RuntimeError("PostgreSQL no devolvió PK para el registro.")

    return int(row[0])


def insert_registro(connection: Any, registro: RegistroLexico) -> int:
    """Compatibilidad: persiste mediante el UPSERT idempotente."""

    return upsert_registro(connection, registro)