"""Persistencia PostgreSQL del Repositorio Léxico Base (RLB).

Este módulo define el foundation reproducible para materializar el
contrato RLB v1.1.0 en PostgreSQL.

No contiene credenciales y no abre conexiones durante importación.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Any

from .models import RegistroLexico


RLB_SCHEMA_VERSION = "1.1.0"
TABLE_NAME = "rlb_registro_lexico"

DDL = """
CREATE TABLE IF NOT EXISTS rlb_registro_lexico (
    pk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    identificador TEXT UNIQUE,
    palabra_puinave TEXT NOT NULL,
    traduccion_espanol TEXT,
    traduccion_ingles TEXT,
    categoria_gramatical TEXT,
    categoria_tematica TEXT,

    tema_cultural TEXT,
    descripcion_cultural TEXT,
    contexto_uso TEXT,
    comunidad TEXT,
    territorio TEXT,

    imagen TEXT,
    audio_puinave TEXT,
    audio_espanol TEXT,
    audio_ingles TEXT,
    video TEXT,

    nivel_acceso TEXT NOT NULL DEFAULT 'pendiente_clasificacion',
    autorizacion_publicacion BOOLEAN NOT NULL DEFAULT FALSE,
    estado_validacion TEXT NOT NULL DEFAULT 'pendiente',

    origen JSONB,
    extensiones JSONB NOT NULL DEFAULT '{}'::jsonb,
    campos_desconocidos JSONB NOT NULL DEFAULT '[]'::jsonb,

    rlb_schema_version TEXT NOT NULL DEFAULT '1.1.0',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT rlb_registro_lexico_palabra_nonblank
        CHECK (btrim(palabra_puinave) <> '')
);


CREATE INDEX IF NOT EXISTS idx_rlb_registro_lexico_palabra
    ON rlb_registro_lexico (palabra_puinave);

CREATE INDEX IF NOT EXISTS idx_rlb_registro_lexico_estado
    ON rlb_registro_lexico (estado_validacion);
""".strip()


